"""
Writes the checklist of implemented MJCF tags that the MJCF reference page (`docs/reference/mujoco_mojo/mjcf.md`) includes as a snippet.

The tree is read off the `children` fields of the XMLModel classes, starting at `Mujoco`, so it cannot drift from the code. Elements the MuJoCo schema has that mojo deliberately does not implement are listed from `mjcf_schema_ignore.txt` (its `unimplemented:` entries).

The same element can be nested under several parents (a frame holds the same children as a body, for example). Its own children are listed only where it is first reached, breadth first, and every other place it appears is a single line.

Usage:
    python scripts/gen_mjcf_tags.py           # rewrite the checklist
    python scripts/gen_mjcf_tags.py --check   # exit 1 if the checklist is out of date, changing nothing

The pre-commit hook `gen-mjcf-tags` runs it when the MJCF classes change, and a test fails if the committed checklist is stale.
"""

from __future__ import annotations

import sys
from collections import deque
from pathlib import Path

from check_mjcf_spec_coverage import load_ignore_file
from mjcf_python_tree import child_fields

from mujoco_mojo.mjcf import Mujoco
from mujoco_mojo.mjcf.xml_model import XMLModel

SCRIPTS = Path(__file__).parent
OUTPUT = SCRIPTS / "generated" / "implemented_mjcf_tags.md"
IGNORE_FILE = SCRIPTS / "mjcf_schema_ignore.txt"

HEADER = "<!-- Generated by scripts/gen_mjcf_tags.py from the MJCF classes. Do not edit by hand; the gen-mjcf-tags pre-commit hook keeps it current. -->"

INDENT = "    "
WORD_JOINER = "⁠"
"""Keeps `parent/child` from being broken across lines after the slash."""

UNIMPLEMENTED_PARENTS = {
    "numeric": "custom",
    "text": "custom",
    "tuple": "custom",
    "element": "tuple",
}
"""Where the unimplemented elements sit in MJCF, so that list reads as a tree too. One that is not listed here (or whose parent is not unimplemented) is shown on its own."""

Node = tuple[str, tuple[type[XMLModel], ...]]
"""An element tag with every class that is written as that tag in one place. Several classes can share a tag (all the geoms are `geom`), and the same tag can mean different things in different places (`plugin` in a body and in the extension)."""


def _children(node: Node) -> list[Node]:
    """The elements nested directly under `node`, in the order the classes declare them, with classes written as the same tag merged."""
    classes_by_tag: dict[str, list[type[XMLModel]]] = {}
    for cls in node[1]:
        for _, child_classes in child_fields(cls):
            for child in child_classes:
                classes = classes_by_tag.setdefault(child.tag, [])
                if child not in classes:
                    classes.append(child)
    return [(tag, tuple(classes)) for tag, classes in classes_by_tag.items()]


def _label(tag: str, parent: str | None) -> str:
    """Direct children of `mujoco` are shown by their bare tag, everything deeper as `parent/child`."""
    return tag if parent in (None, "mujoco") else f"{parent}/{WORD_JOINER}{tag}"


def implemented_tree() -> list[str]:
    """The checklist lines for every implemented element, nested by parent."""
    root: Node = ("mujoco", (Mujoco,))

    # an element is expanded where breadth first search reaches it first
    home: dict[Node, Node | None] = {root: None}
    queue: deque[Node] = deque([root])
    while queue:
        node = queue.popleft()
        for child in _children(node):
            if child not in home:
                home[child] = node
                queue.append(child)

    lines: list[str] = []

    def walk(node: Node, depth: int, parent: str | None) -> None:
        lines.append(f"{INDENT * depth}- [x] {_label(node[0], parent)}")
        for child in _children(node):
            if home[child] == node:
                walk(child, depth + 1, node[0])
            else:
                lines.append(f"{INDENT * (depth + 1)}- [x] {_label(child[0], node[0])}")

    walk(root, 0, None)
    return lines


def unimplemented_tree(tags: set[str]) -> list[str]:
    """The checklist lines for the elements mojo deliberately does not implement, nested by parent."""
    lines: list[str] = []

    def walk(tag: str, depth: int, parent: str | None) -> None:
        lines.append(f"{INDENT * depth}- [ ] {_label(tag, parent)}")
        for child in sorted(t for t in tags if UNIMPLEMENTED_PARENTS.get(t) == tag):
            walk(child, depth + 1, tag)

    for tag in sorted(t for t in tags if UNIMPLEMENTED_PARENTS.get(t) not in tags):
        walk(tag, 0, None)
    return lines


def render() -> str:
    """The full contents of the checklist file."""
    lines = [HEADER, "", *implemented_tree()]

    not_implemented = set(load_ignore_file(IGNORE_FILE).get("unimplemented", ()))
    if not_implemented:
        lines += ["- Not implemented"]
        lines += [f"{INDENT}{line}" for line in unimplemented_tree(not_implemented)]
    return "\n".join(lines) + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv[1:]:
        if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == content:
            return 0
        print(
            f"{OUTPUT.relative_to(SCRIPTS.parent)} is out of date. Run: python scripts/gen_mjcf_tags.py"
        )
        return 1

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
